import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_circles
from sklearn.cluster import SpectralClustering
from sklearn.cluster import spectral_clustering
from sklearn.feature_extraction import image as sk_image
from skimage import data
from skimage.transform import rescale
from skimage.filters import gaussian

X, y = make_circles(n_samples=1000, factor=0.5,
                    noise=0.05, random_state=42)

plt.scatter(X[:, 0], X[:, 1], color='gray')
plt.title("Data Before Spectral Clustering")
plt.savefig("spectral_data_before.png")
plt.show()

spectral = SpectralClustering(n_clusters=2, affinity="nearest_neighbors")
labels = spectral.fit_predict(X)

plt.scatter(X[:, 0], X[:, 1], c=labels)
plt.title("Data After Spectral Clustering")
plt.savefig("spectral_data_after.png")
plt.show()

"""# Dataset 2: Real Image"""

image = data.coins()

print(image.shape)

plt.imshow(image, cmap="gray")
plt.title("Coins Image Before Spectral Clustering")
plt.savefig("spectral_image_before.png")
plt.show()

smooth_image = gaussian(image, sigma=2)
small_image = rescale(smooth_image, 0.2)

graph = sk_image.img_to_graph(small_image)

graph.data = np.exp(-10 * graph.data / graph.data.std())

labels = spectral_clustering(graph, n_clusters=25,assign_labels="discretize")

labels_image = labels.reshape(small_image.shape)

plt.imshow(labels_image, cmap="nipy_spectral")
plt.title("Coins Image After Spectral Clustering")
plt.savefig("spectral_image_after.png")
plt.show()